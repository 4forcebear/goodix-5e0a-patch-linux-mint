#define GOODIX_5E0A_BANDPASS_BACKGROUND_RADIUS (5)
#define GOODIX_5E0A_BANDPASS_TARGET_RMS (80.0f)

/* Packed Milan templates depend on normalization and engine orientation.
 * Reject untagged legacy prints rather than comparing incompatible features. */
#define GOODIX_5E0A_PRINT_FORMAT "milan-bandpass80-native-v1"

/* FDT_UP guard 2000ms / normal 5000ms (ticket 47: a 0x34 timeout means the
 * finger is still down, so the guard path re-issues; success means genuine
 * release); 500dpi ppmm; 128 mid-gray for residual re-centering. */
#define GOODIX_5E0A_FDT_UP_GUARD_TIMEOUT_MS (2000)
#define GOODIX_5E0A_FDT_UP_TIMEOUT_MS (5000)
#define GOODIX_5E0A_PPMM (500.0 / 25.4)
#define GOODIX_5E0A_NORMALIZE_MIDPOINT (128.0f)

/* Best-of-N per-touch capture: bank 4 frames (~132ms settling burst)
 * inside SCAN_5E0A_GET_IMAGE and submit the highest Milan quality / contrast frame. */
#define GOODIX_5E0A_FRAMES_PER_TOUCH (4)

/* FDT_DOWN empty-poll stop-loss: a zero-length reply is retried after 50ms
 * (transient empties happen), but a device answering empty forever is dead.
 * 200 consecutive empties (~10s+ of polling) fail the scan SSM instead of
 * looping until the client gives up. Valid replies reset the count. */
#define GOODIX_5E0A_DOWN_EMPTY_POLL_MAX (200)


